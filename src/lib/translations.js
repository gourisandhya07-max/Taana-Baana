/**
 * Returns a product object with localized title, description, and tags
 */
export function getLocalizedProduct(prod, lang = 'en') {
  if (!prod) return prod;
  if (lang === 'en') return prod;
  const loc = LOCALIZED_PRODUCTS[prod.id]?.[lang];
  if (!loc) return prod;
  return {
    ...prod,
    title: loc.title || prod.title,
    description: loc.description || prod.description,
    tags: loc.tags || prod.tags
  };
}

/**
 * Localizes craft categories for badge and filter displays
 */
export function getLocalizedCategory(cat, lang = 'en') {
  if (!cat) return '';
  const c = cat.toLowerCase();
  if (lang === 'ml') {
    if (c.includes('weav') || c.includes('handloom') || c.includes('saree')) return 'കൈത്തറി & സാരികൾ';
    if (c.includes('pott') || c.includes('clay') || c.includes('terra')) return 'മൺപാത്ര നിർമ്മാണം';
    if (c.includes('wood')) return 'തടി പണികൾ';
    if (c.includes('metal') || c.includes('dhokra') || c.includes('brass')) return 'ലോഹ ശിൽപ്പങ്ങൾ';
    if (c.includes('embro') || c.includes('chikan')) return 'എംബ്രോയിഡറി & തയ്യൽ';
    if (c.includes('leather')) return 'തോൽ ഉൽപ്പന്നങ്ങൾ';
    return cat;
  }
  if (lang === 'hi') {
    if (c.includes('weav') || c.includes('handloom') || c.includes('saree')) return 'हथकरघा बुनाई और साड़ी';
    if (c.includes('pott') || c.includes('clay') || c.includes('terra')) return 'मिट्टी के बर्तन';
    if (c.includes('wood')) return 'लकड़ी की कला';
    if (c.includes('metal') || c.includes('dhokra') || c.includes('brass')) return 'ढोकरा और पीतल कला';
    if (c.includes('embro') || c.includes('chikan')) return 'चिकनकारी और कड़ाई';
    if (c.includes('leather')) return 'हस्तनिर्मित चमड़ा';
    return cat;
  }
  return cat;
}

/**
 * Localizes region strings for artisan locations and filters
 */
export function getLocalizedRegion(region, lang = 'en') {
  if (!region) return '';
  if (lang === 'ml') {
    if (region.includes('Kerala')) return region.replace('Kerala', 'കേരളം').replace('Chendamangalam', 'ചേന്ദമംഗലം');
    if (region.includes('Rajasthan')) return region.replace('Rajasthan', 'രാജസ്ഥാൻ').replace('Molela', 'മൊളേല');
    if (region.includes('Uttar Pradesh')) return region.replace('Uttar Pradesh', 'ഉത്തർപ്രദേശ്').replace('Lucknow', 'ലക്നൗ');
    if (region.includes('Chhattisgarh')) return region.replace('Chhattisgarh', 'ഛത്തീസ്ഗഢ്').replace('Bastar', 'ബസ്തർ');
    if (region.includes('Kashmir')) return region.replace('Kashmir', 'കശ്മീർ');
    return region;
  }
  if (lang === 'hi') {
    if (region.includes('Kerala')) return region.replace('Kerala', 'केरल').replace('Chendamangalam', 'चेन्दमंगलम');
    if (region.includes('Rajasthan')) return region.replace('Rajasthan', 'राजस्थान').replace('मोलेला', 'मोलेला');
    if (region.includes('Uttar Pradesh')) return region.replace('Uttar Pradesh', 'उत्तर प्रदेश').replace('Lucknow', 'लखनऊ');
    if (region.includes('Chhattisgarh')) return region.replace('Chhattisgarh', 'छत्तीसगढ़').replace('Bastar', 'बस्तर');
    if (region.includes('Kashmir')) return region.replace('Kashmir', 'कश्मीर');
    return region;
  }
  return region;
}
